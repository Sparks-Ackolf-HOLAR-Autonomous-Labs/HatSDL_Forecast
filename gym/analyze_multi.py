"""Tables and figure for E3c (complex multi-agent questions on AURORA).

    python -m gym.analyze_multi <dir with e3c_*.jsonl>  ->  results/aurora_multi/e3c_summary.md, fig_e3c_multi.png
"""
from __future__ import annotations

import json
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "aurora_multi"
CELLS = [("single_archive", "today", "summary"), ("single_all", "today", "summary"), ("team", "today", "summary"),
         ("single_all", "projected", "summary"), ("team", "projected", "summary"), ("team", "projected", "raw")]
LABEL = {"single_archive": "one agent, archive tools only", "single_all": "one agent, all tools",
         "team": "coordinator + 5 specialists"}
MISSING = re.compile(r"(no (stacking|device|transport|stack)|not (available|exist|built|recorded|contain)|does not "
                     r"(exist|contain|have)|do not exist|no data|no records|could not|cannot|absent|lack|missing|"
                     r"unavailable|not in the (data|records|archive))", re.I)


def five(ans):
    """Number of distinct numbered items 1-5 in the answer's last third (the next-experiment list)."""
    tail = ans[len(ans) // 3:]
    return len({m for m in re.findall(r"(?m)^\s*(?:[#*\-]+\s*)?\**\s*(?:Experiment\s*)?([1-5])[.):]", tail)})


def metrics(r):
    tools = r["tools"]
    calls = r["calls"]
    sql = r["sql"]
    lit = [t for t in tools if t["tool"] == "search_papers"]
    ans = r.get("answer") or ""
    roles = {c["role"] for c in calls}
    m = {
        "t_total": r["t_total"],
        "model_s": sum(c.get("model_s", 0) for c in calls),
        "coord_model_s": sum(c.get("model_s", 0) for c in calls if c["role"] in ("coordinator", "single")),
        "db_s": sum(q["db_s"] for q in sql),
        "lit_s": sum(t["busy_s"] for t in lit),
        "n_model_calls": len(calls),
        "tokens_out": sum(c.get("completion_tokens", 0) for c in calls),
        "n_agents": len(roles - {"coordinator", "single"}),
        "n_sql": len(sql),
        "sql_err": sum(bool(q["err"]) for q in sql),
        "sql_timeout": sum("timeout" in (q["err"] or "") for q in sql),
        "max_sql_s": max([q["db_s"] for q in sql] or [0]),
        "n_lit": len(lit),
        "finished": not ans.startswith("[") and len(ans) > 200,
        "five": five(ans) >= 5,
        "states_missing": bool(MISSING.search(ans)),
        "cites": bool(re.search(r"10\.\d{4,}/|\(\d{4}\)|et al\.", ans)),
        "lit_grounded": bool(lit) and bool(re.search(r"10\.\d{4,}/|\(\d{4}\)|et al\.", ans)),
        "twist_numbers": bool(re.search(r"1\.(0|05|1|10|15)\s*°|1\.(0|05|1|10|15)\s*deg", ans)),
    }
    if sql:
        first = min(q["t"] for q in sql)
        coord_first = [c for c in calls if c["role"] == "coordinator"]
        m["plan_lead_s"] = (first - (coord_first[0]["t"] + coord_first[0]["model_s"])) if coord_first else None
        m["db_idle_frac"] = 1 - m["db_s"] / max(r["t_total"], 1e-9)
    return m


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else float("nan")


def rng(xs):
    xs = sorted(x for x in xs if x is not None)
    if not xs:
        return "-"
    return f"{xs[int(0.1 * (len(xs) - 1))]:.0f}-{xs[int(round(0.9 * (len(xs) - 1)))]:.0f}"


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    OUT.mkdir(parents=True, exist_ok=True)
    data = {}
    for arm, cond, db in CELLS:
        f = src / f"e3c_{arm}_{cond}_{db}.jsonl"
        if f.exists():
            data[(arm, cond, db)] = [json.loads(x) for x in f.read_text().splitlines() if x.strip()]
    lines = ["# E3c summary (generated by gym/analyze_multi.py)", "",
             "| Arm | AURORA records | DB mode | n | Median decision (s) | 10-90 % (s) | Model calls | Agents asked | "
             "SQL statements | SQL errors / timeouts | Slowest SQL (s) | Database share | Literature (s) |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    rubric = ["", "| Arm | AURORA records | DB mode | Finished | Five experiments listed | Says what the data cannot "
              "answer | Cites papers | Cites after a literature search | Names a twist angle |",
              "|---|---|---|---|---|---|---|---|---|"]
    allm = {}
    for key, recs in data.items():
        ms = [metrics(r) for r in recs]
        allm[key] = ms
        arm, cond, db = key
        n = len(ms)
        share = med([m["db_s"] / m["t_total"] for m in ms])
        lines.append(f"| {LABEL[arm]} | {cond} | {db} | {n} | {med([m['t_total'] for m in ms]):.0f} | "
                     f"{rng([m['t_total'] for m in ms])} | {med([m['n_model_calls'] for m in ms]):.0f} | "
                     f"{med([m['n_agents'] for m in ms]):.0f} | {med([m['n_sql'] for m in ms]):.0f} | "
                     f"{sum(m['sql_err'] for m in ms)} / {sum(m['sql_timeout'] for m in ms)} | "
                     f"{med([m['max_sql_s'] for m in ms]):.2f} | {100 * share:.2f} % | {med([m['lit_s'] for m in ms]):.1f} |")
        pct = lambda k: f"{sum(m[k] for m in ms)}/{n}"  # noqa: E731
        rubric.append(f"| {LABEL[arm]} | {cond} | {db} | {pct('finished')} | {pct('five')} | {pct('states_missing')} | "
                      f"{pct('cites')} | {pct('lit_grounded')} | {pct('twist_numbers')} |")
    leads = [m.get("plan_lead_s") for k, ms in allm.items() if k[0] == "team" for m in ms]
    lines += rubric + ["", f"Team runs: time from the coordinator's first plan to the first database statement, "
                           f"median {med(leads):.1f} s (range {rng(leads)} s)."]
    (OUT / "e3c_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    (OUT / "e3c_metrics.json").write_text(json.dumps({"|".join(k): v for k, v in allm.items()}, indent=1))
    fig(allm)


def fig(allm):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    keys = [k for k in CELLS if k in allm]
    names = {("single_archive", "today", "summary"): "archive\nagent\n(today)",
             ("single_all", "today", "summary"): "one agent,\nall tools\n(today)",
             ("team", "today", "summary"): "team\n\n(today)",
             ("single_all", "projected", "summary"): "one agent,\nall tools\n(projected)",
             ("team", "projected", "summary"): "team\n\n(projected)",
             ("team", "projected", "raw"): "team, no\nsummary table\n(projected)"}
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(7.4, 3.1), gridspec_kw={"width_ratios": [1.5, 1]})
    for i, k in enumerate(keys):
        ys = [m["t_total"] for m in allm[k]]
        a1.scatter([i] * len(ys), ys, s=10, color="#4a6fa5", alpha=0.6, zorder=3)
        a1.hlines(st.median(ys), i - 0.3, i + 0.3, color="#1b2a41", lw=2, zorder=4)
        db = [m["db_s"] for m in allm[k]]
        a1.scatter([i + 0.12] * len(db), [max(d, 0.01) for d in db], s=8, marker="x", color="#c0504d", zorder=3)
    a1.set_yscale("log")
    a1.set_xticks(range(len(keys)), [names[k] for k in keys], fontsize=6.5)
    a1.set_ylabel("seconds per question", fontsize=8)
    a1.tick_params(axis="y", labelsize=7)
    a1.set_title("decision time (dots) and database time (x)", fontsize=8)
    a1.grid(axis="y", alpha=0.3)
    comps = [("finished", "finished"), ("five", "five experiments"), ("states_missing", "names missing data"),
             ("lit_grounded", "cites after search")]
    w = 0.8 / len(keys)
    for i, k in enumerate(keys):
        vals = [100 * sum(m[c] for m in allm[k]) / len(allm[k]) for c, _ in comps]
        a2.bar([j + i * w for j in range(len(comps))], vals, w, label=names[k].replace("\n", " "))
    a2.set_xticks([j + 0.4 - w / 2 for j in range(len(comps))], [c[1] for c in comps], fontsize=6.5, rotation=20)
    a2.set_ylabel("% of runs", fontsize=8)
    a2.tick_params(axis="y", labelsize=7)
    a2.legend(fontsize=5.5, loc="upper center", bbox_to_anchor=(0.5, -0.32), ncol=2, frameon=False)
    a2.set_title("what the answer contains", fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "fig_e3c_multi.png", dpi=200, bbox_inches="tight")


if __name__ == "__main__":
    main()
