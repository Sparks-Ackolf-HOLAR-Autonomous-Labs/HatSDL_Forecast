"""Tables and figure for E3 (agents in the loop). Reads results/aurora_agents/e3_*.jsonl."""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

D = Path(__file__).resolve().parent.parent / "results" / "aurora_agents"
LABEL = {"A": "a: specialist agent, AURORA tools", "A-V": "a: specialist agent + tile image (VLM)",
         "B": "b: generic agent, skills + own SQL"}


def load(name):
    f = D / name
    return [json.loads(x) for x in f.read_text().splitlines() if x.strip()] if f.exists() else []


def q(v, p):
    v = sorted(v)
    return v[min(len(v) - 1, int(round(p * (len(v) - 1))))] if v else float("nan")


def main():
    out = ["# E3 summary (generated by gym/analyze_agents.py)", ""]
    mb = json.loads((D / "e3_microbench.json").read_text()) if (D / "e3_microbench.json").exists() else []
    if mb:
        out += ["## Model speed (Qwen3.5-9B, bf16, vLLM, DGX GB10)", "", "| Measure | Tokens | Seconds |", "|---|---|---|"]
        for r in mb:
            out.append(f"| {r['kind']} | {r.get('prompt_tokens') or r.get('completion_tokens')} | {r['s']:.2f} |")
        dec = [r for r in mb if r["kind"] == "decode"]
        if dec:
            d = max(dec, key=lambda r: r["completion_tokens"])
            out += ["", f"Decode rate: {d['completion_tokens'] / d['s']:.1f} tokens/s (single stream)."]
        out.append("")
    cases = {c: load(f"e3_{c}.jsonl") for c in ("A", "A-V", "B")}
    out += ["## One decision, one agent at a time", "",
            "| Case | Decisions | Finished | Median total (s) | p90 total (s) | Model share | Database (ms, median) "
            "| Database share | Turns (median) | Queries (median) | SQL errors | Tokens out (median) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    rows = {}
    for c, rs in cases.items():
        if not rs:
            continue
        tot = [r["t_total"] for r in rs]
        mod = [r["t_model"] for r in rs]
        db = [r["t_db"] for r in rs]
        rows[c] = rs
        out.append(f"| {LABEL[c]} | {len(rs)} | {sum(r['finished'] for r in rs)} | {st.median(tot):.1f} | {q(tot, .9):.1f} "
                   f"| {sum(mod) / sum(tot):.2%} | {st.median(db) * 1000:.1f} | {sum(db) / sum(tot):.3%} "
                   f"| {st.median(r['n_turns'] for r in rs):.0f} | {st.median(r['n_queries'] for r in rs):.0f} "
                   f"| {sum(r['sql_errors'] for r in rs)} | {st.median(r['completion_tokens'] for r in rs):.0f} |")
    out += ["", "Per task (median total s / median database ms):", "", "| Task | " + " | ".join(LABEL[c] for c in rows) + " |",
            "|---|" + "---|" * len(rows)]
    for t in ("research", "planner", "novice", "pid", "ehs", "tile"):
        cells = []
        for c, rs in rows.items():
            v = [r for r in rs if r["task"] == t]
            cells.append(f"{st.median(r['t_total'] for r in v):.1f} s / {st.median(r['t_db'] for r in v) * 1000:.1f} ms"
                         if v else "")
        out.append(f"| {t} | " + " | ".join(cells) + " |")
    # slowest agent-written queries
    if rows.get("B"):
        qs = sorted(((x["db_s"], x["args"].get("query", ""), x["err"]) for r in rows["B"] for tr in r["turns"]
                     for x in tr["tools"] if x["name"] == "run_sql"), reverse=True)[:5]
        out += ["", "Slowest SQL written by the generic agent:", ""]
        for s, sq, err in qs:
            out.append(f"- {s * 1000:.0f} ms{' (error)' if err else ''}: `{' '.join(sq.split())[:220]}`")
    con = load("e3_concurrency.jsonl")
    if con:
        out += ["", "## Several specialist agents at once (one model server)", "",
                "| Agents | Median decision (s) | Max (s) | Database queries/s, all agents | Queries per agent per minute |",
                "|---|---|---|---|---|"]
        for n in sorted({r["n_concurrent"] for r in con}):
            v = [r for r in con if r["n_concurrent"] == n]
            span = v[0]["span_s"]
            nq = sum(r["n_queries"] for r in v)
            out.append(f"| {n} | {st.median(r['t_total'] for r in v):.1f} | {max(r['t_total'] for r in v):.1f} "
                       f"| {nq / span:.2f} | {nq / span / n * 60:.1f} |")
    net = json.loads((D / "e3_network.json").read_text()) if (D / "e3_network.json").exists() else {}
    if net:
        out += ["", "## Network round trip, no model work (median of 8)", "", "| Target | DNS+TCP+TLS (ms) | Total (ms) | HTTP |",
                "|---|---|---|---|"]
        for k, v in net.items():
            ok = sorted((x for x in v if "total" in x), key=lambda x: x["total"])
            if ok:
                m = ok[len(ok) // 2]
                out.append(f"| {k} | {m['tls'] * 1000 if m['tls'] else m['tcp'] * 1000:.0f} | {m['total'] * 1000:.0f} | {m['http']} |")
    (D / "e3_summary.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

    # figure: per-decision time split, log scale
    if rows:
        fig, ax = plt.subplots(figsize=(6.8, 3.6), dpi=200)
        order = [c for c in ("A", "A-V", "B") if c in rows]
        y = range(len(order))
        db = [st.median(r["t_db"] for r in rows[c]) for c in order]
        mod = [st.median(r["t_model"] for r in rows[c]) for c in order]
        lo = [q([r["t_total"] for r in rows[c]], .1) for c in order]
        hi = [q([r["t_total"] for r in rows[c]], .9) for c in order]
        tot = [st.median(r["t_total"] for r in rows[c]) for c in order]
        ax.barh([i + 0.18 for i in y], mod, height=0.34, color="#4C72B0", label="model calls (median)")
        ax.barh([i - 0.18 for i in y], db, height=0.34, color="#DD8452", label="database (median)")
        ax.errorbar(tot, [i + 0.18 for i in y], xerr=[[t - l for t, l in zip(tot, lo)], [h - t for t, h in zip(tot, hi)]],
                    fmt="none", ecolor="k", capsize=3, lw=0.8, label="decision total, 10-90 %")
        ax.axvline(180, color="grey", ls="--", lw=0.8)
        ax.text(180, len(order) - 0.8, " model start-up\n (once per server)", fontsize=7, color="grey", va="top")
        ax.set_xscale("log")
        ax.set_xlim(1e-4, 3000)
        ax.set_yticks(list(y))
        ax.set_yticklabels([LABEL[c] for c in order], fontsize=8)
        ax.set_xlabel("seconds per decision (log scale)", fontsize=8)
        ax.tick_params(labelsize=7)
        ax.legend(fontsize=7, loc="upper center", bbox_to_anchor=(0.4, -0.2), ncol=3, frameon=False)
        fig.tight_layout()
        fig.savefig(D / "fig_e3_agents.png")


if __name__ == "__main__":
    main()
