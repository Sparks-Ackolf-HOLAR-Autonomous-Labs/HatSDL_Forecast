"""Tables and figure for E2c (national open-access demand on AURORA).

    python -m gym.analyze_national
"""
from __future__ import annotations

import glob
import json
import statistics as st

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from gym.aurora_users import OUT  # noqa: E402

BLUE, ORANGE, INK, MUTED = "#2a78d6", "#eb6834", "#222222", "#6b6b6b"
ARMS = [("shared", "one\nshared pool"),
        ("class_limit", "split by\nsign-in"),
        ("machine_limit", "limit on\nagents")]


def load():
    dem = json.loads((OUT / "e2c_demand.json").read_text())
    run = json.loads((OUT / "e2c_run_p6_s1.json").read_text())
    ramp = json.loads((OUT / "e2c_ramp_W_all_p6_s1.json").read_text())
    ag = json.loads((OUT / "e2c_ramp_N4_agents_p6_s1.json").read_text())
    burst = {}
    for f in sorted(glob.glob(str(OUT / "e2c_burst_a400_s*.json"))):
        d = json.loads(open(f).read())
        for arm, x in d["arms"].items():
            burst.setdefault(arm, []).append(x)
    return dem, run, ramp, ag, burst


def during(xs, sel):
    vals = []
    for x in xs:
        m = x["during"]["modes"]
        if sel == "registered":
            vals.append(100 * x["during"]["registered_over"])
        else:
            vals.append(100 * m.get(sel, {}).get("over_share", 0.0))
    return vals


def main():
    dem, run, ramp, ag, burst = load()
    lines = ["# E2c numbers (generated by gym/analyze_national.py)", ""]
    lines += ["## Scenarios served on 6 connections (seed 1, 30 s per scenario)", "",
              "| Scenario | Concurrent users | Actions/s offered | Open traffic share of actions | Actions over target (%) |",
              "|---|---|---|---|---|"]
    served = {s["key"]: s for s in run["steps"]}
    for s in dem["scenarios"]:
        r = served[s["key"]]
        lines.append(f"| {s['key']}: {s['name']} | {s['users_total']:,} | {r['offered_per_s']:.0f} | "
                     f"{100 * s['open_share']:.0f} % | {100 * r['over_share']:.1f} |")
    lines += ["", "## Ramp of the worst-hour mix (W x k)", "",
              "| k | Users | Actions/s | Over target (%) | registered | open |", "|---|---|---|---|---|---|"]
    for s in ramp["steps"]:
        lines.append(f"| {s['k']:g} | {s['users_total']:,} | {s['offered_per_s']:.0f} | {100 * s['over_share']:.1f} | "
                     f"{100 * s['registered_over']:.1f} | {100 * s['open_over']:.1f} |")
    lines += ["", "## Ramp of AI agents on N2 (agents = 50 k)", "",
              "| Agents | Actions/s | Over target (%) | registered | open | staff p95 (ms) |", "|---|---|---|---|---|---|"]
    for s in ag["steps"]:
        lines.append(f"| {round(s['users'].get('agent', 0))} | {s['offered_per_s']:.0f} | {100 * s['over_share']:.1f} | "
                     f"{100 * s['registered_over']:.1f} | {100 * s['open_over']:.1f} | "
                     f"{s['modes'].get('staff', {}).get('p95_ms', 0):.0f} |")
    lines += ["", "## Unannounced surge of 400 agents (40 s), mean over seeds [min-max]", "",
              "| Arm | Seeds | Registered users over target (%) | Anonymous visitors (%) | Agents (%) |",
              "|---|---|---|---|---|"]
    for arm, _ in ARMS:
        xs = burst.get(arm, [])
        if not xs:
            continue
        cell = lambda v: f"{st.mean(v):.1f} [{min(v):.1f}-{max(v):.1f}]"  # noqa: E731
        lines.append(f"| {arm} | {len(xs)} | {cell(during(xs, 'registered'))} | {cell(during(xs, 'visitor'))} | "
                     f"{cell(during(xs, 'agent'))} |")
    (OUT / "e2c_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    # ---------------------------------------------------------------- figure (print size, 7.0 x 2.9 in)
    plt.rcParams.update({"font.size": 8.5, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                         "xtick.color": MUTED, "ytick.color": MUTED})
    fig, (a, b) = plt.subplots(1, 2, figsize=(7.0, 2.9), gridspec_kw=dict(width_ratios=[1.25, 1]))
    sc = dem["scenarios"]
    ys = list(range(len(sc)))[::-1]
    a.axvspan(170, 340, color="#e6e6e6", lw=0, zorder=0)
    a.axvline(64, color=MUTED, lw=1, ls="--", zorder=1)
    a.barh(ys, [served[s["key"]]["offered_per_s"] for s in sc], height=0.6, color=BLUE, zorder=2)
    a.set_yticks(ys, [f"{s['key']}  {s['users_total']:,} users" for s in sc])
    a.set_xlabel("database actions per second, peak hour")
    a.text(255, len(sc) - 0.35, "limit, national mix", ha="center", va="bottom", color=INK, fontsize=7.5)
    a.text(70, -0.75, "limit, year-4 mix (E2b)", ha="left", va="center", color=MUTED, fontsize=7.5)
    a.set_ylim(-1.1, len(sc) + 0.2)
    a.set_title("a  Demand scenarios on 6 connections", loc="left", fontsize=9, color=INK)
    for sp in ("top", "right"):
        a.spines[sp].set_visible(False)

    arms = [x for x in ARMS if x[0] in burst]
    xs = range(len(arms))
    w = 0.36
    for i, (key, col, lab) in enumerate([("registered", BLUE, "registered users"),
                                         ("visitor", ORANGE, "anonymous visitors")]):
        means, lo, hi = [], [], []
        for arm, _ in arms:
            v = during(burst[arm], key)
            means.append(st.mean(v))
            lo.append(st.mean(v) - min(v))
            hi.append(max(v) - st.mean(v))
        pos = [x + (i - 0.5) * (w + 0.03) for x in xs]
        b.bar(pos, means, width=w, color=col, label=lab, zorder=2)
        b.errorbar(pos, means, yerr=[lo, hi], fmt="none", ecolor=INK, elinewidth=0.8, capsize=2, zorder=3)
    b.set_xticks(list(xs), [lab for _, lab in arms])
    b.set_ylabel("actions over target during surge (%)")
    b.set_ylim(0, 105)
    b.legend(frameon=False, fontsize=7.5, loc="center right")
    b.set_title("b  Surge of 400 AI agents", loc="left", fontsize=9, color=INK)
    for sp in ("top", "right"):
        b.spines[sp].set_visible(False)
    fig.tight_layout()
    fig.savefig(OUT / "fig_e2c_national.png", dpi=200)


if __name__ == "__main__":
    main()
