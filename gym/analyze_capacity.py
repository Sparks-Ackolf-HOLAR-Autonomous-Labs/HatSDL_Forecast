"""Capacity tables for E2b (reads and writes ramps on the AURORA copy) -> results/aurora/e2b_summary.md.

    python -m gym.analyze_capacity

Reads the run files written by `python -m gym.aurora_capacity reads|writes ...`
(e2b_<kind>_<arm>_p<pool>_s<seed>[_refine].json); a refinement file adds steps
between those of the first ramp.
"""
from __future__ import annotations

import glob
import json
import re

from gym.aurora_users import OUT


def runs(kind: str):
    out = {}
    for f in sorted(glob.glob(str(OUT / f"e2b_{kind}_*_p*_s*.json"))):
        m = re.search(rf"e2b_{kind}_(\w+?)_p(\d+)_s(\d+)(_refine)?\.json$", f)
        if not m:
            continue
        d = json.loads(open(f).read())
        key = (m.group(1), int(m.group(2)))
        steps = out.setdefault(key, {})
        for s in d["steps"]:
            steps[s["k"]] = s
    return out


def main():
    lines = ["# E2b numbers (generated by gym/analyze_capacity.py)", "",
             "Year-4 user mix scaled by k, one seed, 30 s per step. A step passes if at most 1 % of user actions",
             "miss their latency target and no action is still queued at the end.", "",
             "## Reads (writes at the year-4 rate): share of user actions over target", ""]
    rd = runs("reads")
    cols = [("production", 6), ("plan", 6), ("plan", 12)]
    ks = sorted({k for c in cols for k in rd.get(c, {})})
    lines += ["| k | Active users | Actions/s | " + " | ".join(f"{a}, {p} conn." for a, p in cols) + " |",
              "|---|---|---|" + "---|" * len(cols)]
    for k in ks:
        first = next(rd[c][k] for c in cols if k in rd.get(c, {}))
        cells = []
        for c in cols:
            s = rd.get(c, {}).get(k)
            cells.append("" if s is None else f"{100 * s['over_share']:.1f} %"
                         + (f" ({s['undrained']} queued)" if s["undrained"] else ""))
        lines.append(f"| {k} | {first['users']:,} | {first['offered_per_s']:.0f} | " + " | ".join(cells) + " |")
    lines += ["", "## Reads: last passing step", ""]
    for c in cols:
        ok = [s for k, s in sorted(rd.get(c, {}).items()) if s["over_share"] <= 0.01 and not s["undrained"]]
        if ok:
            lines.append(f"- {c[0]}, {c[1]} connections: {ok[-1]['users']:,} users, {ok[-1]['offered_per_s']:.0f} actions/s")
    lines += ["", "## Writes (readers at the year-4 stage): one serial tile-and-flakes stream", "",
              "| Arm | Tiles/min offered | Tiles/min written | Write p95 (ms) | Readers over target |", "|---|---|---|---|---|"]
    for (arm, pool), steps in sorted(runs("writes").items()):
        for k, s in sorted(steps.items()):
            lines.append(f"| {arm}, {pool} conn. | {s['tiles_per_min_offered']:,.0f} | {s['tiles_per_min']:,.0f} | "
                         f"{s['write_p95_ms']:.1f} | {100 * s['over_share']:.1f} % |")
    (OUT / "e2b_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
